/*
 * Build-time icon map generator.
 *
 * Scans public/settings.json and every file under src/ (except src/generated/)
 * for icon names, validates each candidate against the real library exports,
 * and emits src/generated/icon-map.js with tree-shakeable named imports.
 *
 * This replaces the old runtime approach (barrel imports of whole icon
 * families plus a 30-way dynamic-import switch) that shipped every icon in
 * react-icons — ~35 MB of JS — to serve roughly 90 icons. Icon names only
 * ever come from settings.json and source literals, never constructed at
 * runtime, so a build-time scan is complete by definition.
 *
 * Run: node scripts/generate-icon-map.js
 * Wired into: npm run build (before vite) and the dev-server settings watcher.
 */

/* global process */

import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, "..")
const OUT_FILE = path.join(ROOT, "src", "generated", "icon-map.js")

// react-icons families, longest prefix first so "Fa6"/"Hi2"/"Io5" are not
// swallowed by "Fa"/"Hi"/"Io". [prefix, module, fallbackModule]
const FAMILIES = [
	["Tfi", "tfi"],
	["Vsc", "vsc"],
	["Fa6", "fa6"],
	["Hi2", "hi2"],
	["Io5", "io5"],
	["Ai", "ai"],
	["Bi", "bi"],
	["Bs", "bs"],
	["Cg", "cg"],
	["Ci", "ci"],
	["Di", "di"],
	["Fa", "fa", "fa6"], // newer FontAwesome icons exist only in fa6
	["Fc", "fc"],
	["Fi", "fi"],
	["Gi", "gi"],
	["Go", "go"],
	["Gr", "gr"],
	["Hi", "hi", "hi2"], // heroicons v2 names share the Hi prefix
	["Im", "im"],
	["Io", "io"],
	["Lu", "lu"],
	["Md", "md"],
	["Pi", "pi"],
	["Ri", "ri"],
	["Rx", "rx"],
	["Si", "si"],
	["Sl", "sl"],
	["Tb", "tb"],
	["Ti", "ti"],
	["Wi", "wi"],
]

const PREFIX_ALT = FAMILIES.map(([p]) => p).join("|")
const REACT_ICON_RE = new RegExp(`\\b(?:${PREFIX_ALT})[A-Z][A-Za-z0-9]*\\b`, "g")
// settings.json also carries heroicon-style names ("AcademicCapIcon", ...)
// resolved from @heroicons/react/24/outline
const HEROICON_RE = /\b[A-Z][A-Za-z0-9]*Icon\b/g

function collectSourceText() {
	const chunks = [fs.readFileSync(path.join(ROOT, "public", "settings.json"), "utf8")]
	const walk = (dir) => {
		for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
			const full = path.join(dir, entry.name)
			if (entry.isDirectory()) {
				if (entry.name === "generated") continue // never scan our own output
				walk(full)
			} else if (/\.(js|jsx)$/.test(entry.name)) {
				chunks.push(fs.readFileSync(full, "utf8"))
			}
		}
	}
	walk(path.join(ROOT, "src"))
	return chunks.join("\n")
}

function familyFor(name) {
	for (const fam of FAMILIES) {
		if (name.startsWith(fam[0])) return fam
	}
	return null
}

async function main() {
	const text = collectSourceText()

	const reactCandidates = new Set(text.match(REACT_ICON_RE) || [])
	const heroCandidates = new Set(text.match(HEROICON_RE) || [])

	// module name -> Set of icon names confirmed exported by that module
	const resolved = new Map()
	const moduleCache = new Map()
	const loadModule = async (spec) => {
		if (!moduleCache.has(spec)) moduleCache.set(spec, await import(spec))
		return moduleCache.get(spec)
	}
	const add = (mod, name) => {
		if (!resolved.has(mod)) resolved.set(mod, new Set())
		resolved.get(mod).add(name)
	}

	const skipped = []
	for (const name of [...reactCandidates].sort()) {
		const fam = familyFor(name)
		if (!fam) continue
		const [, mod, fallbackMod] = fam
		const primary = await loadModule(`react-icons/${mod}`)
		if (name in primary) {
			add(`react-icons/${mod}`, name)
			continue
		}
		if (fallbackMod) {
			const fallback = await loadModule(`react-icons/${fallbackMod}`)
			if (name in fallback) {
				add(`react-icons/${fallbackMod}`, name)
				continue
			}
		}
		skipped.push(name)
	}

	const heroModule = await loadModule("@heroicons/react/24/outline")
	for (const name of [...heroCandidates].sort()) {
		if (name in heroModule) add("@heroicons/react/24/outline", name)
		// non-matches are ordinary identifiers ending in "Icon" — not an error
	}

	const modules = [...resolved.keys()].sort()
	const lines = [
		"// AUTO-GENERATED by scripts/generate-icon-map.js — do not edit by hand.",
		"// Regenerate with: node scripts/generate-icon-map.js",
		"// Contains every icon name found in public/settings.json and src/**.",
		"",
	]
	for (const mod of modules) {
		const names = [...resolved.get(mod)].sort()
		lines.push(`import {`)
		for (const n of names) lines.push(`\t${n},`)
		lines.push(`} from "${mod}"`)
	}
	lines.push("", "export const ICON_MAP = {")
	for (const mod of modules) {
		for (const n of [...resolved.get(mod)].sort()) lines.push(`\t${n},`)
	}
	lines.push("}", "")

	const content = lines.join("\n")
	fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true })
	const existing = fs.existsSync(OUT_FILE) ? fs.readFileSync(OUT_FILE, "utf8") : null
	if (existing !== content) {
		fs.writeFileSync(OUT_FILE, content)
	}

	const total = [...resolved.values()].reduce((a, s) => a + s.size, 0)
	console.log(
		`✓ icon map: ${total} icons across ${modules.length} modules${existing === content ? " (unchanged)" : ""}`
	)
	if (skipped.length) {
		console.warn(`⚠️ unresolved icon-like names (not exported by their family): ${skipped.join(", ")}`)
	}
}

main().catch((err) => {
	console.error(`❌ icon map generation failed: ${err.message}`)
	process.exit(1)
})
