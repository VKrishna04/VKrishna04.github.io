#!/usr/bin/env node
/**
 * verify-attribution.js
 * Confirms the project credit survived the bundler and the prerenderer.
 * Run: node scripts/verify-attribution.js (last step of `npm run build`)
 *
 * pre-build-validation.js already refuses to build when the credit has been
 * taken out of the *source*, but a source check cannot see what actually
 * shipped: a tree-shake, a Footer edit or a stray prerender change could drop
 * the credit from dist/ while every source file still looks correct. This reads
 * the built output instead, so the only way to publish without the credit is to
 * publish without building.
 *
 * The credit is deliberately spread across surfaces that are generated by
 * different scripts — footer markup, meta tags, JSON-LD, robots.txt,
 * humans.txt, llms.txt, the JSON endpoints and a served copy of NOTICE. No
 * single edit removes it, and each surface is regenerated on every build, so a
 * removal has to be made in source, in several places, in a diff that shows it.
 *
 * The credit is required by NOTICE under Apache License section 4(d). It is the
 * only identity in this project that a fork may not change — everything about
 * the *site owner* comes from settings.json and should change.
 */

/* global process */

import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"
import { ATTRIBUTION } from "../src/utils/attribution.js"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.join(__dirname, "..")
const DIST = path.join(ROOT, "dist")

const htmlFiles = []
const jsFiles = []

const walk = (dir) => {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const full = path.join(dir, entry.name)
		if (entry.isDirectory()) walk(full)
		else if (entry.name.endsWith(".html")) htmlFiles.push(full)
		else if (entry.name.endsWith(".js")) jsFiles.push(full)
	}
}

if (!fs.existsSync(DIST)) {
	console.error("❌ dist/ not found - run this after the build, not before")
	process.exit(1)
}
walk(DIST)

const { author, github, repository, generator } = ATTRIBUTION
const failures = []

/** Reads a file under dist/, or null when it was never generated. */
const dist = (rel) => {
	const full = path.join(DIST, rel)
	return fs.existsSync(full) ? fs.readFileSync(full, "utf8") : null
}

const listMissing = (files, label) =>
	`${label} (${files.length} of ${htmlFiles.length} pages):\n` +
	files
		.slice(0, 5)
		.map((f) => `     ${path.relative(DIST, f)}`)
		.join("\n")

// --- 1. The rendered footer -------------------------------------------------
// The footer renders the author name inside a link, so the two facts land in
// the markup separately. Both have to be there for the credit to read as one.
const html = new Map(htmlFiles.map((f) => [f, fs.readFileSync(f, "utf8")]))

const missingFooter = htmlFiles.filter(
	(f) => !html.get(f).includes(author) || !html.get(f).includes(github)
)
if (missingFooter.length) {
	failures.push(listMissing(missingFooter, "credit missing from the markup"))
}

// --- 2. The meta tags -------------------------------------------------------
// scripts/inject-seo.js writes these. They survive a footer redesign, which is
// the most likely way to lose the credit by accident.
const missingMeta = htmlFiles.filter(
	(f) =>
		!html.get(f).includes('name="generator"') ||
		!html.get(f).includes(generator)
)
if (missingMeta.length) {
	failures.push(listMissing(missingMeta, 'no <meta name="generator"> credit'))
}

// --- 3. The structured data -------------------------------------------------
// The WebSite JSON-LD node names the creator. Machines read this one.
const missingLd = htmlFiles.filter((f) => !html.get(f).includes('"creator"'))
if (missingLd.length) {
	failures.push(listMissing(missingLd, "no creator in the JSON-LD"))
}

// --- 4. The JavaScript bundle -----------------------------------------------
// So pages rendered client-side carry it too.
if (!jsFiles.some((f) => fs.readFileSync(f, "utf8").includes(author))) {
	failures.push("credit missing from every JavaScript chunk in dist/")
}

// --- 5. The plain-text surfaces ---------------------------------------------
// humans.txt and NOTICE.txt are unconditional. llms.txt and robots.txt are
// only checked when they exist: seo.crawling can legitimately switch them off,
// and a site owner declining to publish machine-readable data is not tampering.
const humans = dist("humans.txt")
if (humans === null) {
	failures.push("dist/humans.txt was not generated")
} else if (!humans.includes(author) || !humans.includes(repository)) {
	failures.push("dist/humans.txt no longer carries the credit")
}

const notice = dist("NOTICE.txt")
if (notice === null) {
	failures.push("dist/NOTICE.txt was not generated")
} else if (!notice.includes(author)) {
	failures.push("dist/NOTICE.txt no longer credits the original author")
}

const robots = dist("robots.txt")
if (robots !== null && !robots.includes(repository)) {
	failures.push("dist/robots.txt no longer carries the credit header")
}

const llms = dist("llms.txt")
if (llms !== null && !llms.includes(author)) {
	failures.push("dist/llms.txt no longer has a Credits section")
}

// --- 6. The JSON endpoints --------------------------------------------------
const apiDir = path.join(DIST, "api")
if (fs.existsSync(apiDir)) {
	for (const name of fs.readdirSync(apiDir).filter((f) => f.endsWith(".json"))) {
		let parsed
		try {
			parsed = JSON.parse(fs.readFileSync(path.join(apiDir, name), "utf8"))
		} catch {
			failures.push(`dist/api/${name} is not valid JSON`)
			continue
		}
		if (parsed?._attribution?.builtBy !== author) {
			failures.push(`dist/api/${name} has no _attribution.builtBy credit`)
		}
	}
}

// --- 7. The file the licence actually names ---------------------------------
const rootNotice = path.join(ROOT, "NOTICE")
if (
	!fs.existsSync(rootNotice) ||
	!fs.readFileSync(rootNotice, "utf8").includes(author)
) {
	failures.push("NOTICE is missing or no longer credits the original author")
}

if (failures.length) {
	console.error("❌ Attribution missing from the built site")
	failures.forEach((f) => console.error(`   ${f}`))
	console.error(
		`\n   The credit "${ATTRIBUTION.credit}" is required by NOTICE under`
	)
	console.error("   Apache License section 4(d). Restore it and rebuild.")
	process.exit(1)
}

console.log(
	`✓ Attribution present in ${htmlFiles.length} pages (markup, meta, JSON-LD),` +
		` the JS bundle, humans.txt, NOTICE.txt and the JSON endpoints`
)
